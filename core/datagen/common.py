"""Phase 4: helpers shared by the data generators in scripts/.

Rules from the master plan (section 4.4): a fixed seed per generator,
everything keyed on person_id, no activity after a person's death,
data regenerated by scripts and never committed.
"""

import json
from datetime import date, timedelta

import duckdb
import numpy as np
import pandas as pd

from core.sql.catalog import load
from src.common.config import PROJECT_ROOT, get_settings

WORLD = PROJECT_ROOT / "data" / "world"
GEN = WORLD / "gen"
META_FILE = GEN / "_meta.json"


def synthea(name: str, columns: list) -> pd.DataFrame:
    """Read selected columns of one Synthea CSV as text, and check they exist."""
    path = get_settings().synthea_dir / name
    if not path.exists():
        raise SystemExit(f"Synthea file not found: {path}")
    head = pd.read_csv(path, nrows=0).columns.tolist()
    missing = [c for c in columns if c not in head]
    if missing:
        raise SystemExit(f"{name}: missing columns {missing}\nColumns: {head}")
    return pd.read_csv(path, usecols=columns, dtype=str, keep_default_na=False)


def world(name: str) -> pd.DataFrame:
    """Read a Phase 0 world table (data/world/<name>.parquet)."""
    path = WORLD / f"{name}.parquet"
    if not path.exists():
        raise SystemExit(f"Phase 0 table not found: {path}")
    return duckdb.sql(f"SELECT * FROM read_parquet('{path.as_posix()}')").df()


def gen(name: str) -> pd.DataFrame:
    """Read a table written by an earlier Phase 4 generator."""
    path = GEN / f"{name}.parquet"
    if not path.exists():
        raise SystemExit(
            f"{path.name} not found. Run the generator that makes it first."
        )
    frame = duckdb.sql(f"SELECT * FROM read_parquet('{path.as_posix()}')").df()
    for column, col in load()["tables"][name]["columns"].items():
        if col["type"] == "DATE":
            frame[column] = [d.date() if pd.notna(d) else None for d in frame[column]]
    return frame


def write(name: str, frame: pd.DataFrame, folder=None) -> int:
    """Write one table with exactly the columns and types in its catalogue."""
    spec = load()["tables"][name]
    wanted = list(spec["columns"])
    missing = [c for c in wanted if c not in frame.columns]
    extra = [c for c in frame.columns if c not in wanted]
    if missing or extra:
        raise SystemExit(f"{name}: missing {missing}, unexpected {extra}")
    folder = folder or GEN
    folder.mkdir(parents=True, exist_ok=True)
    target = folder / f"{name}.parquet"
    select = ", ".join(
        f'CAST("{c}" AS {spec["columns"][c]["type"]}) AS "{c}"' for c in wanted
    )
    con = duckdb.connect()
    con.register("frame", frame[wanted])
    con.execute(
        f"COPY (SELECT {select} FROM frame) TO '{target.as_posix()}' (FORMAT parquet)"
    )
    count = con.execute(f"SELECT COUNT(*) FROM '{target.as_posix()}'").fetchone()[0]
    con.close()
    print(f"{name:17} rows {count:>9,}")
    return count


def ids(prefix: str, n: int, width: int) -> list:
    return [f"{prefix}{i:0{width}d}" for i in range(1, n + 1)]


def to_date(text: pd.Series) -> pd.Series:
    """Synthea dates and timestamps to Python dates (empty text becomes NaT)."""
    return pd.to_datetime(text.str[:10].replace("", None), errors="coerce").dt.date


def save_meta(**values):
    GEN.mkdir(parents=True, exist_ok=True)
    meta = read_meta() if META_FILE.exists() else {}
    meta.update({k: str(v) for k, v in values.items()})
    META_FILE.write_text(json.dumps(meta, indent=2), encoding="utf-8")


def read_meta() -> dict:
    if not META_FILE.exists():
        raise SystemExit("data/world/gen/_meta.json not found. Run gen_hospital first.")
    return json.loads(META_FILE.read_text(encoding="utf-8"))


def data_end() -> date:
    return date.fromisoformat(read_meta()["data_end"])


def random_dates(rng, low: pd.Series, high: pd.Series) -> pd.Series:
    """One random date per row between low and high (inclusive)."""
    low = pd.to_datetime(low)
    span = (pd.to_datetime(high) - low).dt.days.clip(lower=0).to_numpy()
    offset = np.floor(rng.random(len(span)) * (span + 1)).astype(int)
    return (low + pd.to_timedelta(offset, unit="D")).dt.date


def add_years(day: date, years: int) -> date:
    try:
        return day.replace(year=day.year + years)
    except ValueError:
        return day + timedelta(days=365 * years)


def id_map(file: str, prefix: str, width: int) -> dict:
    """Synthea ID to project ID, numbered in file order (stable across scripts)."""
    frame = synthea(file, ["Id"])
    return dict(zip(frame["Id"], ids(prefix, len(frame), width), strict=True))


def person_map() -> dict:
    person = world("person")
    return dict(zip(person["synthea_id"], person["person_id"], strict=True))


def drop_after_death(frame: pd.DataFrame, column: str, label: str) -> pd.DataFrame:
    """Rule 3: no activity after death or after the end of the data."""
    death = gen("person")[["person_id", "death_date"]]
    merged = frame.merge(death, on="person_id", how="left")
    day = pd.to_datetime(merged[column])
    late = (day > pd.to_datetime(merged["death_date"])) | (
        day > pd.Timestamp(data_end())
    )
    if late.any():
        print(
            f"  {label}: {int(late.sum())} source rows after death or data end removed"
        )
    return frame[~late.to_numpy()].reset_index(drop=True)
